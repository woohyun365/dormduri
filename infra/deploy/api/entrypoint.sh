#!/usr/bin/env sh
set -eu

required_env="DATABASE_URL DIRECT_URL RETENTION_WORKER_DATABASE_URL RETENTION_DISCLOSURE_DATABASE_URL MIGRATION_DATABASE_URL LOG_HASH_SECRET METRICS_BEARER_TOKEN VERIFICATION_CODE_HMAC_SECRET ROOMMATE_SEARCH_CURSOR_HMAC_SECRET PROFILE_DETAIL_ENTRY_TOKEN_HMAC_SECRET CHAT_THREAD_LIST_CURSOR_HMAC_SECRET"

for name in $required_env; do
  eval "value=\${$name:-}"
  if [ -z "$value" ]; then
    echo "missing required env: $name" >&2
    exit 64
  fi
done

exec "$@"
