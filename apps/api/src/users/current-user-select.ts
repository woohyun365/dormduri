export function buildUserWithProfileSelect(seasonId: string | null) {
  return {
    id: true,
    email: true,
    emailVerifiedAt: true,
    gender: true,
    campus: true,
    dormitoryId: true,
    dormitorySelectionState: true,
    seasonParticipants: seasonId
      ? {
          where: { seasonId },
          take: 1,
          select: {
            id: true,
            seasonId: true,
            userId: true,
            participationIntent: true,
            registeredAt: true,
            declinedAt: true,
            dormitoryId: true,
            dormitorySelectionState: true,
            participantStatus: true,
            campusCodeSnapshot: true,
            genderSnapshot: true,
            joinedAt: true,
            activatedAt: true,
            matchedAt: true,
            withdrawnAt: true,
            expiredAt: true,
            hiddenByAdminAt: true,
            hiddenReasonCode: true,
            hiddenReasonDetail: true,
            deactivatedAt: true,
            createdAt: true,
            updatedAt: true,
            profile: {
              select: {
                participantId: true,
                nicknameSnapshot: true,
                nicknameNormalizedSnapshot: true,
                lifestyle: true,
                intro: true,
                messageToRoommate: true,
                collegeCode: true,
                grade: true,
                mbti: true,
                birthYear: true,
                templateSourceUserProfileUpdatedAt: true,
                createdAt: true,
                updatedAt: true,
              },
            },
          },
        }
      : undefined,
    profile: {
      select: {
        userId: true,
        nickname: true,
        nicknameNormalized: true,
        nicknameChangedAt: true,
        lifestyle: true,
        intro: true,
        messageToRoommate: true,
        collegeCode: true,
        grade: true,
        mbti: true,
        birthYear: true,
        createdAt: true,
        updatedAt: true,
      },
    },
  } as const;
}
