import Joi from 'joi';
import {
  DEFAULT_DATABASE_ADAPTER_CONNECT_TIMEOUT_MS,
  DEFAULT_DATABASE_ADAPTER_IDLE_TIMEOUT_MS,
  DEFAULT_DATABASE_APPLICATION_NAME,
  DEFAULT_DATABASE_POOL_MAX,
  DEFAULT_DATABASE_POOL_MIN,
  DEFAULT_DATABASE_QUERY_TIMEOUT_MS,
  DEFAULT_DATABASE_STATEMENT_TIMEOUT_MS,
  DEFAULT_DATABASE_URL,
  DEFAULT_PRISMA_QUERY_LOG_EVENTS,
  DEFAULT_RETENTION_DISCLOSURE_DATABASE_APPLICATION_NAME,
  DEFAULT_RETENTION_WORKER_DATABASE_APPLICATION_NAME,
} from '../database.config.js';
import {
  booleanEnv,
  numberEnv,
  productionRequiredString,
  type EnvSchemaDefinition,
} from './joi-helpers.js';

export const databaseEnvSchema = {
  DATABASE_URL: productionRequiredString({
    nonProductionDefault: DEFAULT_DATABASE_URL,
    forbidProductionPlaceholder: true,
  }),
  DIRECT_URL: Joi.string().trim().optional(),
  RETENTION_WORKER_DATABASE_URL: productionRequiredString({ forbidProductionPlaceholder: true }),
  RETENTION_DISCLOSURE_DATABASE_URL: productionRequiredString({
    forbidProductionPlaceholder: true,
  }),
  MIGRATION_DATABASE_URL: Joi.string().trim().optional(),
  DATABASE_ADAPTER_CONNECT_TIMEOUT_MS: numberEnv(DEFAULT_DATABASE_ADAPTER_CONNECT_TIMEOUT_MS, {
    min: 1,
  }),
  DATABASE_ADAPTER_IDLE_TIMEOUT_MS: numberEnv(DEFAULT_DATABASE_ADAPTER_IDLE_TIMEOUT_MS, {
    min: 1,
  }),
  DATABASE_POOL_MAX: numberEnv(DEFAULT_DATABASE_POOL_MAX, { min: 1 }),
  DATABASE_POOL_MIN: numberEnv(DEFAULT_DATABASE_POOL_MIN, { min: 0 }),
  DATABASE_QUERY_TIMEOUT_MS: numberEnv(DEFAULT_DATABASE_QUERY_TIMEOUT_MS, { min: 0 }),
  DATABASE_STATEMENT_TIMEOUT_MS: numberEnv(DEFAULT_DATABASE_STATEMENT_TIMEOUT_MS, { min: 0 }),
  DATABASE_APPLICATION_NAME: Joi.string().trim().default(DEFAULT_DATABASE_APPLICATION_NAME),
  RETENTION_WORKER_DATABASE_APPLICATION_NAME: Joi.string()
    .trim()
    .default(DEFAULT_RETENTION_WORKER_DATABASE_APPLICATION_NAME),
  RETENTION_DISCLOSURE_DATABASE_APPLICATION_NAME: Joi.string()
    .trim()
    .default(DEFAULT_RETENTION_DISCLOSURE_DATABASE_APPLICATION_NAME),
  PRISMA_QUERY_LOG_EVENTS: booleanEnv(DEFAULT_PRISMA_QUERY_LOG_EVENTS),
} satisfies EnvSchemaDefinition;
