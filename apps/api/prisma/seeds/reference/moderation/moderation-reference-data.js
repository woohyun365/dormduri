export function normalizeForModeration(value) {
  return value
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[\s\p{P}\p{S}_]+/gu, '');
}

function blockedRows(policyCategory, terms, matchMode = 'INCLUDES', surface = 'ALL') {
  return terms.map((term) => ({
    referenceKey: `blocked:${policyCategory}:${surface.toLowerCase()}:${normalizeForModeration(term)}`,
    term,
    normalizedTerm: normalizeForModeration(term),
    category: 'BLOCKED_TEXT',
    matchMode,
    surface,
    policyCategory,
    isActive: true,
  }));
}

function reservedRows(terms) {
  return terms.map(({ term, matchMode }) => ({
    referenceKey: `reserved:nickname:${normalizeForModeration(term)}`,
    term,
    normalizedTerm: normalizeForModeration(term),
    category: 'RESERVED_NICKNAME',
    matchMode,
    surface: 'NICKNAME',
    policyCategory: 'RESERVED_IDENTITY',
    isActive: true,
  }));
}

