export function validateModerationReferenceData(rows = MODERATION_REFERENCE_DATA) {
  const referenceKeys = new Set();
  const policyIdentities = new Set();

  for (const row of rows) {
    if (!row.referenceKey) {
      throw new Error('Moderation referenceKey is required.');
    }
    if (referenceKeys.has(row.referenceKey)) {
      throw new Error(`Duplicate moderation referenceKey: ${row.referenceKey}`);
    }
    referenceKeys.add(row.referenceKey);

    const expectedNormalizedTerm = normalizeForModeration(row.term);
    if (!expectedNormalizedTerm || row.normalizedTerm !== expectedNormalizedTerm) {
      throw new Error(`Invalid moderation normalizedTerm: ${row.referenceKey}`);
    }

    const policyIdentity = [row.normalizedTerm, row.category, row.matchMode, row.surface].join(':');
    if (policyIdentities.has(policyIdentity)) {
      throw new Error(`Duplicate moderation policy identity: ${policyIdentity}`);
    }
    policyIdentities.add(policyIdentity);
  }

  return rows;
}
